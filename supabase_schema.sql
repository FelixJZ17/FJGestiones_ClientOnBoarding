create table if not exists public.questionnaire_submissions (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    name text not null,
    email text not null,
    phone text not null,
    quiz_score text not null,
    consent boolean not null default false,
    ip_hash text not null,
    payload_json jsonb not null
);

alter table public.questionnaire_submissions enable row level security;

create table if not exists public.budget_requests (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    name text not null,
    email text not null,
    phone text not null,
    consent boolean not null default false,
    ip_hash text not null,
    payload_json jsonb not null
);

alter table public.budget_requests enable row level security;

create table if not exists public.aeat_payment_events (
    id bigint generated by default as identity primary key,
    id_registro text not null,
    cliente text not null,
    modelo text,
    ejercicio integer,
    periodo text,
    resumen_concepto text,
    principal numeric(12, 2),
    intereses numeric(12, 2),
    porcentaje_apremio numeric(6, 3),
    apremio numeric(12, 2),
    total_a_pagar numeric(12, 2),
    fecha_vto date,
    estado text,
    pagado numeric(12, 2) default 0,
    pendiente numeric(12, 2),
    total_plazos integer,
    num_plazo integer,
    cerrado boolean default false,
    check_vencido boolean default false,
    check_pagado boolean default false,
    observaciones text,
    fecha_pago date,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (cliente, id_registro)
);

alter table public.aeat_payment_events enable row level security;

create index if not exists aeat_payment_events_cliente_fecha_idx
    on public.aeat_payment_events (cliente, fecha_vto);
